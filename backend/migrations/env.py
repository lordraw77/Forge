"""Alembic environment: async engine, owner role (migrations are not subject to RLS)."""

from __future__ import annotations

import asyncio

from alembic import context
from sqlalchemy.engine import Connection

from forge.core.db import create_engine
from forge.core.settings import get_settings

config = context.config
target_metadata = None  # schema is written as explicit migrations, not autogenerated


def _run(connection: Connection) -> None:
    context.configure(connection=connection, target_metadata=target_metadata)
    with context.begin_transaction():
        context.run_migrations()


async def _run_async() -> None:
    engine = create_engine(get_settings(), app_role=False)
    async with engine.connect() as connection:
        await connection.run_sync(_run)
    await engine.dispose()


if context.is_offline_mode():
    context.configure(url="postgresql://", literal_binds=True, target_metadata=target_metadata)
    with context.begin_transaction():
        context.run_migrations()
else:
    asyncio.run(_run_async())

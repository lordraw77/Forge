#!/usr/bin/env bash
# Generate local configuration with random secrets. Idempotent: existing files are kept.
#   .env                          bootstrap values (spec: admin + boot values only)
#   deploy/compose/infra.env      infrastructure wiring for Compose (ADR-007)
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
env_file="$root/.env"
infra_file="$root/deploy/compose/infra.env"

rand() { openssl rand -hex "${1:-24}"; }

if [[ -e "$infra_file" ]]; then
  echo "keep    ${infra_file#"$root"/}"
  # shellcheck disable=SC1090
  source "$infra_file"
else
  FORGE_DB_PASSWORD="$(rand)"
  umask 077
  cat > "$infra_file" <<EOF
# Infrastructure wiring for docker compose. Generated by scripts/gen-env.sh. Do not commit.
POSTGRES_PASSWORD=$(rand)
FORGE_DB_NAME=forge
FORGE_DB_USER=forge
FORGE_DB_PASSWORD=$FORGE_DB_PASSWORD
TEMPORAL_DB_PASSWORD=$(rand)
VALKEY_PASSWORD=$(rand)
S3_ACCESS_KEY=forge$(rand 6)
S3_SECRET_KEY=$(rand)
EOF
  echo "create  ${infra_file#"$root"/}"
  # shellcheck disable=SC1090
  source "$infra_file"
fi

if [[ -e "$env_file" ]]; then
  echo "keep    .env"
else
  umask 077
  cat > "$env_file" <<EOF
# Initial administrator, created on first start only
FORGE_ADMIN_USERNAME=admin
FORGE_ADMIN_EMAIL=admin@example.com
FORGE_ADMIN_PASSWORD=$(rand 12)

# Boot values (cannot live in the database they point to)
FORGE_DATABASE_URL=postgresql+asyncpg://${FORGE_DB_USER}:${FORGE_DB_PASSWORD}@db:5432/${FORGE_DB_NAME}
FORGE_MASTER_KEY=$(openssl rand -base64 32)
FORGE_PUBLIC_URL=http://localhost:8080
EOF
  echo "create  .env  (admin password inside; it must be changed at first login)"
fi

#!/usr/bin/env bash
# Generate local configuration with random secrets. Idempotent: existing files are kept.
#   .env                          bootstrap values (spec: admin + boot values only)
#   deploy/compose/infra.env      infrastructure wiring for Compose (ADR-007)
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
env_file="$root/.env"
infra_file="$root/deploy/compose/infra.env"

rand() { openssl rand -hex "${1:-24}"; }

if [[ -e "$infra_file" ]]; then
  echo "keep    ${infra_file#"$root"/}"
  # shellcheck disable=SC1090
  source "$infra_file"
else
  FORGE_DB_PASSWORD="$(rand)"
  umask 077
  cat > "$infra_file" <<EOF
# Infrastructure wiring for docker compose. Generated by scripts/gen-env.sh. Do not commit.
POSTGRES_PASSWORD=$(rand)
FORGE_DB_NAME=forge
FORGE_DB_USER=forge
FORGE_DB_PASSWORD=$FORGE_DB_PASSWORD
TEMPORAL_DB_PASSWORD=$(rand)
VALKEY_PASSWORD=$(rand)
S3_ACCESS_KEY=forge$(rand 6)
S3_SECRET_KEY=$(rand)
GRAFANA_ADMIN_PASSWORD=$(rand 12)
EOF
  echo "create  ${infra_file#"$root"/}"
  # shellcheck disable=SC1090
  source "$infra_file"
fi

# Keys added after a file was generated are appended, never rewritten.
for key in GRAFANA_ADMIN_PASSWORD OPENSEARCH_ADMIN_PASSWORD FORGE_SEARCH_PASSWORD; do
  if ! grep -q "^${key}=" "$infra_file"; then
    echo "${key}=$(rand 16)" >> "$infra_file"
    echo "update  ${infra_file#"$root"/} (${key})"
  fi
done
# Langfuse profile (deploy/compose/langfuse.yml): secrets added after a file was generated.
for key in LANGFUSE_DB_PASSWORD LANGFUSE_CLICKHOUSE_PASSWORD LANGFUSE_NEXTAUTH_SECRET LANGFUSE_SALT \
  LANGFUSE_INIT_USER_PASSWORD; do
  if ! grep -q "^${key}=" "$infra_file"; then
    echo "${key}=$(rand 16)" >> "$infra_file"
    echo "update  ${infra_file#"$root"/} (${key})"
  fi
done
if ! grep -q "^LANGFUSE_ENCRYPTION_KEY=" "$infra_file"; then
  echo "LANGFUSE_ENCRYPTION_KEY=$(rand 32)" >> "$infra_file"  # 64 hex characters, as Langfuse asks
  echo "update  ${infra_file#"$root"/} (LANGFUSE_ENCRYPTION_KEY)"
fi
if ! grep -q "^LANGFUSE_PUBLIC_KEY=" "$infra_file"; then
  pk="pk-lf-$(rand 12)"
  sk="sk-lf-$(rand 12)"
  {
    echo "LANGFUSE_PUBLIC_KEY=$pk"
    echo "LANGFUSE_SECRET_KEY=$sk"
    echo "LANGFUSE_AUTH=$(printf '%s:%s' "$pk" "$sk" | base64 -w0)"
  } >> "$infra_file"
  echo "update  ${infra_file#"$root"/} (Langfuse API keys)"
fi
# shellcheck disable=SC1090
source "$infra_file"

# OpenSearch (ADR-016): own CA and certificates, and the internal users file with bcrypt hashes.
search_dir="$root/deploy/compose/search"
certs="$search_dir/certs"
if [[ ! -e "$certs/node.pem" ]]; then
  mkdir -p "$certs"
  (
    cd "$certs"
    umask 077
    openssl req -x509 -newkey rsa:3072 -nodes -days 3650 -subj "/O=Forge/CN=Forge Search CA" \
      -keyout root-ca-key.pem -out root-ca.pem 2>/dev/null
    issue() {  # name subject [san]
      openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:3072 -out "$1-key.pem" 2>/dev/null
      openssl req -new -key "$1-key.pem" -subj "$2" -out "$1.csr" 2>/dev/null
      printf '%s\n' "${3:-}" > "$1.ext"
      openssl x509 -req -in "$1.csr" -CA root-ca.pem -CAkey root-ca-key.pem -CAcreateserial \
        -days 3650 -sha256 -extfile "$1.ext" -out "$1.pem" 2>/dev/null
      rm -f "$1.csr" "$1.ext"
    }
    issue node "/O=Forge/CN=search" \
      "subjectAltName=DNS:search,DNS:localhost,IP:127.0.0.1"$'\n'"extendedKeyUsage=serverAuth,clientAuth"
    issue admin "/O=Forge/CN=forge-search-admin" "extendedKeyUsage=clientAuth"
    rm -f root-ca.srl
    chmod 644 root-ca.pem  # also read by the backend containers to verify the server
  )
  echo "create  deploy/compose/search/certs"
fi
users="$search_dir/internal_users.yml"
if [[ ! -e "$users" ]]; then
  hash() {
    docker run --rm -e PW="$1" --entrypoint /usr/share/opensearch/plugins/opensearch-security/tools/hash.sh \
      "${OPENSEARCH_IMAGE:-opensearchproject/opensearch:3.9.0}" -env PW 2>/dev/null | tail -1
  }
  admin_hash="$(hash "$OPENSEARCH_ADMIN_PASSWORD")"
  forge_hash="$(hash "$FORGE_SEARCH_PASSWORD")"
  umask 077
  cat > "$users" <<EOF
# Generated by scripts/gen-env.sh. Do not commit. Loaded into the security index on first start.
_meta:
  type: "internalusers"
  config_version: 2
admin:
  hash: "$admin_hash"
  reserved: true
  description: "Operator account"
forge:
  hash: "$forge_hash"
  reserved: true
  description: "Forge application (role forge_app)"
EOF
  echo "create  deploy/compose/search/internal_users.yml"
fi
# The OpenSearch container runs as uid 1000 and must read its keys and users file.
if [[ "$(id -u)" == 0 ]]; then
  chown 1000:1000 "$certs"/node.pem "$certs"/node-key.pem "$certs"/admin.pem "$certs"/admin-key.pem "$users"
  chmod 600 "$certs"/*-key.pem "$users"
else
  chmod 644 "$certs"/node-key.pem "$certs"/admin-key.pem "$users"  # rootless: readable by the container
fi
chmod 600 "$certs/root-ca-key.pem"

if [[ -e "$env_file" ]]; then
  echo "keep    .env"
else
  umask 077
  cat > "$env_file" <<EOF
# Initial administrator, created on first start only
FORGE_ADMIN_USERNAME=admin
FORGE_ADMIN_EMAIL=admin@example.com
FORGE_ADMIN_PASSWORD=$(rand 12)

# Boot values (cannot live in the database they point to)
FORGE_DATABASE_URL=postgresql+asyncpg://${FORGE_DB_USER}:${FORGE_DB_PASSWORD}@db:5432/${FORGE_DB_NAME}
FORGE_MASTER_KEY=$(openssl rand -base64 32)
FORGE_PUBLIC_URL=http://localhost:8080
EOF
  echo "create  .env  (admin password inside; it must be changed at first login)"
fi
